android {
    namespace = "com.taller.inventario"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.taller.inventario"
        minSdk = 24
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        create("release") {
            val keyStorePath = localProperties.getProperty("RELEASE_KEYSTORE_PATH")
                ?: System.getenv("RELEASE_KEYSTORE_PATH")
                ?: "release.jks"
            val keyStorePassword = localProperties.getProperty("RELEASE_KEYSTORE_PASSWORD")
                ?: System.getenv("RELEASE_KEYSTORE_PASSWORD")
                ?: "taller123456"
            val keyAliasName = localProperties.getProperty("RELEASE_KEY_ALIAS")
                ?: System.getenv("RELEASE_KEY_ALIAS")
                ?: "tallerkey"
            val keyPasswordVal = localProperties.getProperty("RELEASE_KEY_PASSWORD")
                ?: System.getenv("RELEASE_KEY_PASSWORD")
                ?: "taller123456"

            val storeFileObj = file(keyStorePath)
            if (storeFileObj.exists()) {
                storeFile = storeFileObj
                storePassword = keyStorePassword
                keyAlias = keyAliasName
                keyPassword = keyPasswordVal
            }
        }
    }

    buildTypes {
        debug {
            enableUnitTestCoverage = true
        }
        release {
            isMinifyEnabled = false
            val releaseSigning = signingConfigs.getByName("release")
            if (releaseSigning.storeFile != null && releaseSigning.storeFile!!.exists()) {
                signingConfig = releaseSigning
            }
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
    }
}

